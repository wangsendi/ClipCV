import AppKit
import Testing
@testable import ClipCV

@MainActor
struct ClipboardRulesTests {
    private let stringType = ClipboardRules.Kind.string
    private let rtfType = ClipboardRules.Kind.rtf
    private let pngType = ClipboardRules.Kind.png
    private let fileType = ClipboardRules.Kind.fileURL

    @Test func ignoresTransientConcealedAndInternalTypes() {
        #expect(ClipboardRules.shouldIgnore(types: ["org.nspasteboard.TransientType", stringType]))
        #expect(ClipboardRules.shouldIgnore(types: ["org.nspasteboard.ConcealedType"]))
        #expect(ClipboardRules.shouldIgnore(types: ["org.nspasteboard.AutoGeneratedType"]))
        #expect(ClipboardRules.shouldIgnore(types: [ClipboardRules.Kind.internalMarker, stringType]))
        #expect(!ClipboardRules.shouldIgnore(types: [stringType, rtfType]))
    }

    @Test func skipsEmptyStringWithoutRichContent() {
        let empty = ClipboardPayload(type: stringType, data: Data("   \n".utf8))
        let text = ClipboardPayload(type: stringType, data: Data("你好".utf8))
        #expect(ClipboardRules.normalize([[empty]], enabled: ClipboardRules.supportedTypes).isEmpty)
        let stored = ClipboardRules.normalize([[text]], enabled: ClipboardRules.supportedTypes)
        #expect(stored == [text])
    }

    @Test func dropsDisabledTypesAndMergesDuplicates() {
        let text = ClipboardPayload(type: stringType, data: Data("same".utf8))
        let image = ClipboardPayload(type: pngType, data: Data([0x89, 0x50]))
        let enabled: Set<String> = [stringType]
        let stored = ClipboardRules.normalize([[text, image], [text]], enabled: enabled)
        #expect(stored == [text])
    }

    @Test func duplicateFingerprintMatchesLatestContents() {
        let first = [ClipboardPayload(type: stringType, data: Data("abc".utf8))]
        let reordered = [ClipboardPayload(type: stringType, data: Data("abc".utf8))]
        let different = [ClipboardPayload(type: stringType, data: Data("xyz".utf8))]
        #expect(ClipboardRules.isDuplicate(latest: first, new: reordered))
        #expect(!ClipboardRules.isDuplicate(latest: first, new: different))
    }

    @Test(arguments: [
        ("https://example.com/Report.pdf", "https://example.com/report.pdf"),
        ("https://example.com/?token=AbC", "https://example.com/?token=abc"),
        ("https://example.com/?Token=abc", "https://example.com/?token=abc"),
        ("https://example.com/#Section", "https://example.com/#section"),
    ])
    func distinctURLsAreNotMerged(_ urls: (String, String)) {
        let first = [ClipboardPayload(type: stringType, data: Data(urls.0.utf8))]
        let second = [ClipboardPayload(type: stringType, data: Data(urls.1.utf8))]
        #expect(!ClipboardRules.isDuplicate(latest: first, new: second))
    }

    @Test func URLDeduplicationNormalizesHostAndRemovesTrackingParameters() {
        let original = "HTTPS://EXAMPLE.COM/Report.pdf?token=AbC&utm_source=test"
        let cleaned = "https://example.com/Report.pdf?token=AbC"
        let first = [ClipboardPayload(type: stringType, data: Data(original.utf8))]
        let second = [ClipboardPayload(type: stringType, data: Data(cleaned.utf8))]
        #expect(ClipboardRules.isDuplicate(latest: first, new: second))
    }

    @Test func plainPasteKeepsOnlyStringWhenTextExists() {
        let text = ClipboardPayload(type: stringType, data: Data("标题".utf8))
        let rich = ClipboardPayload(type: rtfType, data: Data("{\\rtf1 rich}".utf8))
        let plain = ClipboardRules.payloadsRemovingFormatting([rich, text])
        #expect(plain.count == 1)
        #expect(plain[0].type == stringType)
        #expect(String(data: plain[0].data, encoding: .utf8) == "标题")
    }

    @Test(arguments: [1, 2])
    func plainPastePreservesFilesAlongsideTheirText(count: Int) {
        let files = (0..<count).map { index in
            let url = URL(fileURLWithPath: "/tmp/王森迪1108-\(index).docx")
            return ClipboardPayload(type: fileType, data: Data(url.absoluteString.utf8))
        }
        let text = ClipboardPayload(type: stringType, data: Data("王森迪1108.docx".utf8))
        let rich = ClipboardPayload(type: rtfType, data: Data("{\\rtf1 filename}".utf8))

        let plain = ClipboardRules.payloadsRemovingFormatting([rich, text] + files)

        #expect(plain == [text] + files)
        #expect(ClipboardRules.fileURLs(from: plain).count == count)
        #expect(ClipboardRules.payloadsRemovingFormatting(files) == files)
    }

    @Test(arguments: [1, 2], [false, true])
    func restoringFileHistoryPreservesRepresentationsWithFilesFirst(count: Int, removeFormatting: Bool) throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        let directory = FileManager.default.temporaryDirectory.resolvingSymlinksInPath()
            .appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        let urls = ["王森迪1108.docx", "ClipCV.xcodeproj"].prefix(count).map {
            directory.appendingPathComponent($0)
        }
        try Data("file fixture".utf8).write(to: urls[0])
        if count > 1 {
            try FileManager.default.createDirectory(at: urls[1], withIntermediateDirectories: true)
        }
        let files = urls.map { ClipboardPayload(type: fileType, data: Data($0.absoluteString.utf8)) }
        let text = ClipboardPayload(type: stringType, data: Data("王森迪1108.docx".utf8))
        let payloads = [text] + files
        pasteboard.setString("overwritten", forType: .string)

        ClipboardWriter.write(
            removeFormatting ? ClipboardRules.payloadsRemovingFormatting(payloads) : payloads,
            to: pasteboard
        )

        let restored = try #require(pasteboard.readObjects(
            forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]
        ) as? [URL])
        #expect(restored == urls)
        #expect(pasteboard.pasteboardItems?.count == count)
        #expect(pasteboard.pasteboardItems?.first?.types.first == .fileURL)
        #expect(pasteboard.string(forType: .string) == "王森迪1108.docx")
        #expect(pasteboard.propertyList(forType: .init("NSFilenamesPboardType")) as? [String] == urls.map(\.path))
        #expect(pasteboard.data(forType: .init(ClipboardRules.Kind.internalMarker)) == Data([1]))
    }

    @Test func restoringFinderFileReferencePreservesItsOriginalBytes() throws {
        let directory = FileManager.default.temporaryDirectory.resolvingSymlinksInPath()
            .appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        let file = directory.appendingPathComponent("中文 空格 100%.docx")
        let content = Data("file fixture".utf8)
        try content.write(to: file)
        let reference = try #require(CFURLCreateFileReferenceURL(nil, file as CFURL, nil)).takeRetainedValue()
        let raw = CFURLGetString(reference) as String
        let data = Data(raw.utf8)
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }

        ClipboardWriter.write([ClipboardPayload(type: fileType, data: data)], to: pasteboard)

        #expect(raw.hasPrefix("file:///.file/id="))
        #expect(pasteboard.data(forType: .fileURL) == data)
        let restored = try #require(pasteboard.readObjects(
            forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]
        ) as? [URL])
        #expect(restored.count == 1)
        let restoredFile = try #require(restored.first)
        #expect(try Data(contentsOf: restoredFile) == content)
        let path = try #require((pasteboard.propertyList(forType: .init("NSFilenamesPboardType")) as? [String])?.first)
        #expect(try Data(contentsOf: URL(fileURLWithPath: path)) == content)
    }

    @Test func restoringRichTextPreservesFormattingInOneItem() {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        let text = ClipboardPayload(type: stringType, data: Data("标题".utf8))
        let rich = ClipboardPayload(type: rtfType, data: Data("{\\rtf1 title}".utf8))

        ClipboardWriter.write([text, rich], to: pasteboard)

        #expect(pasteboard.string(forType: .string) == "标题")
        #expect(pasteboard.data(forType: .rtf) == rich.data)
        #expect(pasteboard.pasteboardItems?.count == 1)
        #expect(pasteboard.data(forType: .init(ClipboardRules.Kind.internalMarker)) == Data([1]))
    }

    @Test func titleCollapsesWhitespaceAndTruncates() {
        let spaced = ClipboardPayload(type: stringType, data: Data("第一行\n\n第二行".utf8))
        #expect(ClipboardRules.title(for: [spaced]) == "第一行 第二行")

        let long = String(repeating: "字", count: 250)
        let truncated = ClipboardRules.title(for: [ClipboardPayload(type: stringType, data: Data(long.utf8))])
        #expect(truncated.count == 201)
        #expect(truncated.hasSuffix("…"))
    }

    @Test func titleUsesFileNameOrImageLabel() {
        let file = ClipboardPayload(type: fileType, data: Data("file:///Users/me/报告.pdf".utf8))
        #expect(ClipboardRules.title(for: [file]) == "报告.pdf")
        let image = ClipboardPayload(type: pngType, data: Data([0x00, 0x01]))
        #expect(ClipboardRules.title(for: [image]) == ClipboardRules.TitleToken.image)
        #expect(ClipboardRules.localizedTitle(ClipboardRules.TitleToken.image) == L10n.t(.categoryImage))
        #expect(ClipboardRules.isGenericImageTitle(ClipboardRules.TitleToken.image))
    }

    @Test(arguments: ["图片", "Image", "富文本", "Rich Text", "剪贴板内容", "Clipboard Content"])
    func literalTextTitlesArePreserved(_ title: String) {
        #expect(ClipboardRules.localizedTitle(title) == title)
        #expect(!ClipboardRules.isGenericImageTitle(title))
    }

    @Test func deletionCountRemovesOldestUnpinnedOverflow() {
        #expect(ClipboardRules.deletionCount(total: 200, unpinned: 200, limit: 200) == 0)
        #expect(ClipboardRules.deletionCount(total: 205, unpinned: 180, limit: 200) == 5)
        #expect(ClipboardRules.deletionCount(total: 230, unpinned: 10, limit: 200) == 10)
    }

    @Test func deletionCountForSizeDropsOldestUntilUnderLimit() {
        let sizes: [Int64] = [100, 200, 300, 400]
        let total: Int64 = 1000
        #expect(ClipboardRules.deletionCountForSize(
            unpinnedSizesOldestFirst: sizes, totalBytes: total, limitBytes: 0
        ) == 0)
        #expect(ClipboardRules.deletionCountForSize(
            unpinnedSizesOldestFirst: sizes, totalBytes: total, limitBytes: 1000
        ) == 0)
        #expect(ClipboardRules.deletionCountForSize(
            unpinnedSizesOldestFirst: sizes, totalBytes: total, limitBytes: 700
        ) == 2)
        #expect(ClipboardRules.deletionCountForSize(
            unpinnedSizesOldestFirst: sizes, totalBytes: total, limitBytes: 50
        ) == 4)
    }
}
