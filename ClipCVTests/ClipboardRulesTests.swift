import AppKit
import Testing
@testable import ClipCV

@MainActor
struct ClipboardRulesTests {
    private let stringType = ClipboardRules.Kind.string
    private let rtfType = ClipboardRules.Kind.rtf
    private let pngType = ClipboardRules.Kind.png
    private let fileType = ClipboardRules.Kind.fileURL

    @Test func ignoresTransientConcealedAndInternalTypes() {
        #expect(ClipboardRules.shouldIgnore(types: ["org.nspasteboard.TransientType", stringType]))
        #expect(ClipboardRules.shouldIgnore(types: ["org.nspasteboard.ConcealedType"]))
        #expect(ClipboardRules.shouldIgnore(types: ["org.nspasteboard.AutoGeneratedType"]))
        #expect(ClipboardRules.shouldIgnore(types: [ClipboardRules.Kind.internalMarker, stringType]))
        #expect(!ClipboardRules.shouldIgnore(types: [stringType, rtfType]))
    }

    @Test func skipsEmptyStringWithoutRichContent() {
        let empty = ClipboardPayload(type: stringType, data: Data("   \n".utf8))
        let text = ClipboardPayload(type: stringType, data: Data("你好".utf8))
        #expect(ClipboardRules.normalize([[empty]], enabled: ClipboardRules.supportedTypes).isEmpty)
        let stored = ClipboardRules.normalize([[text]], enabled: ClipboardRules.supportedTypes)
        #expect(stored == [text])
    }

    @Test func dropsDisabledTypesAndMergesDuplicates() {
        let text = ClipboardPayload(type: stringType, data: Data("same".utf8))
        let image = ClipboardPayload(type: pngType, data: Data([0x89, 0x50]))
        let enabled: Set<String> = [stringType]
        let stored = ClipboardRules.normalize([[text, image], [text]], enabled: enabled)
        #expect(stored == [text])
    }

    @Test func duplicateFingerprintMatchesLatestContents() {
        let first = [ClipboardPayload(type: stringType, data: Data("abc".utf8))]
        let reordered = [ClipboardPayload(type: stringType, data: Data("abc".utf8))]
        let different = [ClipboardPayload(type: stringType, data: Data("xyz".utf8))]
        #expect(ClipboardRules.isDuplicate(latest: first, new: reordered))
        #expect(!ClipboardRules.isDuplicate(latest: first, new: different))
    }

    @Test func plainPasteKeepsOnlyStringWhenTextExists() {
        let text = ClipboardPayload(type: stringType, data: Data("标题".utf8))
        let rich = ClipboardPayload(type: rtfType, data: Data("{\\rtf1 rich}".utf8))
        let plain = ClipboardRules.payloadsRemovingFormatting([rich, text])
        #expect(plain.count == 1)
        #expect(plain[0].type == stringType)
        #expect(String(data: plain[0].data, encoding: .utf8) == "标题")
    }

    @Test func titleCollapsesWhitespaceAndTruncates() {
        let spaced = ClipboardPayload(type: stringType, data: Data("第一行\n\n第二行".utf8))
        #expect(ClipboardRules.title(for: [spaced]) == "第一行 第二行")

        let long = String(repeating: "字", count: 250)
        let truncated = ClipboardRules.title(for: [ClipboardPayload(type: stringType, data: Data(long.utf8))])
        #expect(truncated.count == 201)
        #expect(truncated.hasSuffix("…"))
    }

    @Test func titleUsesFileNameOrImageLabel() {
        let file = ClipboardPayload(type: fileType, data: Data("file:///Users/me/报告.pdf".utf8))
        #expect(ClipboardRules.title(for: [file]) == "报告.pdf")
        let image = ClipboardPayload(type: pngType, data: Data([0x00, 0x01]))
        #expect(ClipboardRules.title(for: [image]) == ClipboardRules.TitleToken.image)
        #expect(ClipboardRules.localizedTitle(ClipboardRules.TitleToken.image) == L10n.t(.categoryImage))
        #expect(ClipboardRules.localizedTitle("图片") == L10n.t(.categoryImage))
        #expect(ClipboardRules.isGenericImageTitle("Image"))
    }

    @Test func deletionCountRemovesOldestUnpinnedOverflow() {
        #expect(ClipboardRules.deletionCount(total: 200, unpinned: 200, limit: 200) == 0)
        #expect(ClipboardRules.deletionCount(total: 205, unpinned: 180, limit: 200) == 5)
        #expect(ClipboardRules.deletionCount(total: 230, unpinned: 10, limit: 200) == 10)
    }

    @Test func deletionCountForSizeDropsOldestUntilUnderLimit() {
        let sizes: [Int64] = [100, 200, 300, 400]
        let total: Int64 = 1000
        #expect(ClipboardRules.deletionCountForSize(
            unpinnedSizesOldestFirst: sizes, totalBytes: total, limitBytes: 0
        ) == 0)
        #expect(ClipboardRules.deletionCountForSize(
            unpinnedSizesOldestFirst: sizes, totalBytes: total, limitBytes: 1000
        ) == 0)
        #expect(ClipboardRules.deletionCountForSize(
            unpinnedSizesOldestFirst: sizes, totalBytes: total, limitBytes: 700
        ) == 2)
        #expect(ClipboardRules.deletionCountForSize(
            unpinnedSizesOldestFirst: sizes, totalBytes: total, limitBytes: 50
        ) == 4)
    }
}
