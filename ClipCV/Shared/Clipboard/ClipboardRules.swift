import Foundation

struct ClipboardPayload: Equatable, Sendable {
    var type: String
    var data: Data
}

enum ClipboardRules {
    enum Kind {
        static let string = "public.utf8-plain-text"
        static let url = "public.url"
        static let rtf = "public.rtf"
        static let html = "public.html"
        static let png = "public.png"
        static let tiff = "public.tiff"
        static let jpeg = "public.jpeg"
        static let heic = "public.heic"
        static let fileURL = "public.file-url"
        static let internalMarker = "wangsendi.ClipCV.internal"
        static let source = "org.nspasteboard.source"
    }

    static let supportedTypes: Set<String> = [
        Kind.string, Kind.url, Kind.rtf, Kind.html, Kind.png, Kind.tiff, Kind.jpeg, Kind.heic, Kind.fileURL,
    ]

    static let imageTypes = [Kind.png, Kind.jpeg, Kind.heic, Kind.tiff]

    static func isImageType(_ type: String) -> Bool { imageTypes.contains(type) }

    private static let ignoredMarkers: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        Kind.internalMarker,
    ]

    private static let trackingParams: Set<String> = [
        "utm_source", "utm_medium", "utm_campaign", "utm_term", "utm_content",
        "fbclid", "gclid", "mc_cid", "mc_eid",
    ]

    static func shouldIgnore(types: Set<String>) -> Bool {
        !types.isDisjoint(with: ignoredMarkers)
    }

    static func isDuplicate(latest: [ClipboardPayload], new: [ClipboardPayload]) -> Bool {
        guard !latest.isEmpty, !new.isEmpty else { return false }
        if fingerprint(latest) == fingerprint(new) { return true }
        guard let left = normalizedURLString(from: latest),
              let right = normalizedURLString(from: new)
        else { return false }
        return left == right
    }

    static func normalizedURLString(from contents: [ClipboardPayload]) -> String? {
        guard let text = plainText(from: contents)?.trimmingCharacters(in: .whitespacesAndNewlines),
              var components = URLComponents(string: text),
              let scheme = components.scheme?.lowercased(),
              scheme == "http" || scheme == "https"
        else { return nil }

        components.scheme = scheme
        components.host = components.host?.lowercased()
        let filtered = components.queryItems?.filter { !trackingParams.contains($0.name.lowercased()) }
        components.queryItems = (filtered?.isEmpty == true) ? nil : filtered
        return components.string
    }

    static func normalize(_ items: [[ClipboardPayload]], enabled: Set<String>) -> [ClipboardPayload] {
        var seen = Set<Int>()
        let normalized = items.flatMap { raw -> [ClipboardPayload] in
            let filtered = raw.filter { enabled.contains($0.type) && supportedTypes.contains($0.type) }
            guard !isIgnorableEmpty(filtered) else { return [] }
            return filtered.filter { seen.insert(fingerprint([$0])).inserted }
        }
        return preferPNGOverTIFF(normalized)
    }

    /// Screenshots often ship PNG+TIFF; keep one image payload to cut memory/disk.
    static func preferPNGOverTIFF(_ payloads: [ClipboardPayload]) -> [ClipboardPayload] {
        let hasPNG = payloads.contains { $0.type == Kind.png }
        guard hasPNG else { return payloads }
        return payloads.filter { $0.type != Kind.tiff }
    }

    static func isIgnorableEmpty(_ contents: [ClipboardPayload]) -> Bool {
        guard !contents.isEmpty else { return true }
        guard contents.allSatisfy({ $0.type == Kind.string }) else { return false }
        return contents
            .compactMap { string(from: $0.data) }
            .joined()
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .isEmpty
    }

    static func fingerprint(_ contents: [ClipboardPayload]) -> Int {
        var hasher = Hasher()
        contents.sorted { $0.type < $1.type }.forEach {
            hasher.combine($0.type)
            hasher.combine($0.data)
        }
        return hasher.finalize()
    }

    static func deletionCount(total: Int, unpinned: Int, limit: Int) -> Int {
        guard total > limit else { return 0 }
        return min(unpinned, total - limit)
    }

    static func deletionCountForSize(unpinnedSizesOldestFirst: [Int64], totalBytes: Int64, limitBytes: Int64) -> Int {
        guard limitBytes > 0, totalBytes > limitBytes else { return 0 }
        var remaining = totalBytes
        var count = 0
        for size in unpinnedSizesOldestFirst {
            guard remaining > limitBytes else { break }
            remaining -= size
            count += 1
        }
        return count
    }

    static func byteSize(of item: ClipboardItem) -> Int64 {
        item.storedContents.reduce(Int64(0)) { $0 + Int64($1.value.count) }
    }

    // 保存标题标识，让历史标题能随界面语言切换。
    enum TitleToken {
        static let image = "__clipcv.image__"
        static let richText = "__clipcv.richText__"
        static let generic = "__clipcv.item__"
    }

    static func title(for contents: [ClipboardPayload]) -> String {
        if let files = fileURLText(from: contents), let title = collapsedTitle(from: files, limit: 1_000) {
            return title
        }
        if let text = stringText(from: contents), let title = collapsedTitle(from: text) {
            return title
        }
        if contents.contains(where: { isImageType($0.type) }) {
            return TitleToken.image
        }
        if contents.contains(where: { $0.type == Kind.html || $0.type == Kind.rtf }) {
            return TitleToken.richText
        }
        return TitleToken.generic
    }

    static func isGenericImageTitle(_ stored: String) -> Bool {
        stored == TitleToken.image
    }

    static func collapsedTitle(from text: String, limit: Int = 200) -> String? {
        let trimmed = text
            .replacingOccurrences(of: "\\s+", with: " ", options: .regularExpression)
            .trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }
        return trimmed.count > limit ? String(trimmed.prefix(limit)) + "…" : trimmed
    }

    static func payloadsRemovingFormatting(_ contents: [ClipboardPayload]) -> [ClipboardPayload] {
        if let text = plainText(from: contents) {
            // Finder includes a text representation; removing formatting must preserve the files.
            return [ClipboardPayload(type: Kind.string, data: Data(text.utf8))]
                + contents.filter { $0.type == Kind.fileURL }
        }
        return contents.filter {
            isImageType($0.type) || $0.type == Kind.fileURL
        }
    }

    static func isContentEditable(_ item: ClipboardItem) -> Bool {
        !item.hasImage
            && fileURLs(from: item.payloads).isEmpty
            && plainText(from: item.payloads) != nil
    }

    static func fileURLs(from contents: [ClipboardPayload]) -> [URL] {
        contents.compactMap { payload -> URL? in
            guard payload.type == Kind.fileURL else { return nil }
            if let url = URL(dataRepresentation: payload.data, relativeTo: nil, isAbsolute: true),
               url.isFileURL {
                return url
            }
            guard let raw = string(from: payload.data)?.trimmingCharacters(in: .whitespacesAndNewlines),
                  !raw.isEmpty
            else { return nil }
            if let url = URL(string: raw), url.isFileURL { return url }
            let path = raw.hasPrefix("file://")
                ? (URL(string: raw)?.path ?? String(raw.dropFirst(7)))
                : raw
            return URL(fileURLWithPath: path)
        }
    }

    static func fileURLText(from contents: [ClipboardPayload]) -> String? {
        let paths = fileURLs(from: contents).map {
            $0.absoluteString.removingPercentEncoding ?? $0.absoluteString
        }
        return paths.isEmpty ? nil : paths.joined(separator: "\n")
    }

    static func previewText(for item: ClipboardItem) -> String {
        if let files = fileURLText(from: item.payloads) { return files }
        if let plain = plainText(from: item.payloads), !plain.isEmpty { return plain }
        if let ocr = item.ocrText, !ocr.isEmpty { return ocr }
        // Image-only generic titles are list labels — don't show them as preview body.
        if item.hasImage { return "" }
        return localizedTitle(item.title)
    }

    static func hasTextContent(_ item: ClipboardItem) -> Bool {
        item.storedContents.contains {
            $0.type == Kind.string || $0.type == Kind.url || $0.type == Kind.rtf || $0.type == Kind.html
        }
    }

    static func isFileItem(_ item: ClipboardItem) -> Bool {
        item.storedContents.contains { $0.type == Kind.fileURL }
    }

    static func isWebLinkItem(_ item: ClipboardItem) -> Bool {
        guard !item.hasImage, !isFileItem(item), hasTextContent(item), let text = plainText(from: item.payloads)?.trimmingCharacters(in: .whitespacesAndNewlines),
              let url = URL(string: text),
              let scheme = url.scheme?.lowercased()
        else { return false }
        return ["http", "https", "mailto"].contains(scheme)
    }

    static func isColorItem(_ item: ClipboardItem) -> Bool {
        parseHexRGB(from: item.title) != nil
    }

    static func sourceApps(from items: [ClipboardItem], limit: Int = 16) -> [String] {
        var seen = Set<String>()
        return Array(
            items.compactMap(\.sourceApp)
                .filter { !$0.isEmpty && seen.insert($0).inserted }
                .prefix(limit)
        )
    }

    static func parseHexRGB(from title: String) -> UInt32? {
        let trimmed = title.trimmingCharacters(in: .whitespacesAndNewlines)
        guard trimmed.hasPrefix("#") else { return nil }
        var hex = String(trimmed.dropFirst())
        if hex.count == 3 { hex = hex.map { "\($0)\($0)" }.joined() }
        guard hex.count == 6 else { return nil }
        return UInt32(hex, radix: 16)
    }

    static func stringText(from contents: [ClipboardPayload]) -> String? {
        guard let data = (contents.first(where: { $0.type == Kind.string }) ?? contents.first(where: { $0.type == Kind.url }))?.data,
              let text = string(from: data),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return nil }
        return text
    }

    static func nonEmpty(_ text: String?) -> String? {
        guard let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        return text
    }

    private static func string(from data: Data) -> String? {
        String(data: data, encoding: .utf8) ?? String(data: data, encoding: .utf16)
    }
}
